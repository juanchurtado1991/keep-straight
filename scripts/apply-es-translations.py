def patch_file(path: Path, translations: dict[str, str]) -> int:
    text = path.read_text(encoding="utf-8")
    updated = 0
    for name, value in translations.items():
        pattern = rf'(<string name="{re.escape(name)}">)(.*?)(</string>)'
        escaped = (
            value.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
            .replace("'", "\\'")
        )

        def repl(match: re.Match[str], esc: str = escaped) -> str:
            return f"{match.group(1)}{esc}{match.group(3)}"

        new_text, count = re.subn(pattern, repl, text, count=1, flags=re.DOTALL)
        if count:
            text = new_text
            updated += count
        else:
            print(f"WARN: missing key {name} in {path}", file=sys.stderr)
    path.write_text(text, encoding="utf-8")
    return updated


